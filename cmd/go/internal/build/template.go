package build

// mainTemplate is the generated main.go for a `--native` build. It is
// deliberately tiny: it embeds the baked Config as JSON and hands it to
// buildrt.Main, so all execution logic stays in the shared, tested runtime
// rather than in generated code. The embedded config.json carries the entry
// source and every bundled file, so there is no source text in this template
// to escape — eliminating an entire class of code-generation injection bugs.
//
// It imports github.com/aql-lang/aql/cmd/go/internal/buildrt, which is why the
// generated package must be built inside the cmd/go module tree (Go's
// internal-package visibility rule) — see native.go.
const mainTemplate = `// Code generated by ` + "`aql build --native`" + `. DO NOT EDIT.
package main

import (
	_ "embed"
	"encoding/json"
	"fmt"
	"os"

	"github.com/aql-lang/aql/cmd/go/internal/buildrt"
)

//go:embed config.json
var configJSON []byte

func main() {
	var cfg buildrt.Config
	if err := json.Unmarshal(configJSON, &cfg); err != nil {
		fmt.Fprintf(os.Stderr, "error: corrupt embedded config: %s\n", err)
		os.Exit(1)
	}
	os.Exit(buildrt.Main(cfg, os.Args[1:], os.Stdin, os.Stdout, os.Stderr))
}
`
